-- SENTINELX multi-organisation event store
-- Run this once in Supabase SQL Editor. Do not expose the service-role key in browser code.

create table if not exists public.sx_events (
  id bigint generated by default as identity primary key,
  org_slug text not null,
  session_id text not null,
  username text not null,
  event_type text not null,
  detail text not null,
  risk integer not null default 0 check (risk between 0 and 100),
  severity text not null default 'LOW',
  created_at timestamptz not null default now()
);
create index if not exists sx_events_org_id_idx on public.sx_events (org_slug, id desc);
create index if not exists sx_events_session_idx on public.sx_events (session_id, id desc);

create table if not exists public.sx_sessions (
  session_id text primary key,
  org_slug text not null,
  username text not null,
  risk integer not null default 0 check (risk between 0 and 100),
  status text not null default 'ACTIVE',
  updated_at timestamptz not null default now()
);
create index if not exists sx_sessions_org_idx on public.sx_sessions (org_slug, updated_at desc);

create table if not exists public.sx_login_attempts (
  org_slug text not null,
  username text not null,
  ip_hash text not null,
  count integer not null default 0,
  locked_until timestamptz,
  primary key (org_slug, username, ip_hash)
);

create table if not exists public.sx_contained_sessions (
  session_id text primary key,
  org_slug text not null,
  contained_at timestamptz not null default now()
);
create index if not exists sx_contained_org_idx on public.sx_contained_sessions (org_slug);

-- Deny browser/anon access. The backend uses the server-only service-role key.
alter table public.sx_events enable row level security;
alter table public.sx_sessions enable row level security;
alter table public.sx_login_attempts enable row level security;
alter table public.sx_contained_sessions enable row level security;

-- No anon/authenticated policies are intentionally created for these internal tables.
